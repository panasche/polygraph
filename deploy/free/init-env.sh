#!/usr/bin/env bash
# Create deploy/free/.env and deploy/free/s3.json with fresh random secrets.
#
#   ./deploy/free/init-env.sh
#
# Run it on the server, not on your laptop. It asks for your web address and
# the GitHub App details, and generates every other secret itself. Secret
# input is hidden and never goes on the command line or into shell history.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
env_file="$here/.env"
s3_file="$here/s3.json"

fail() { echo "Error: $*" >&2; exit 1; }

command -v openssl >/dev/null || fail "openssl is not installed (sudo apt-get install -y openssl)."
if [[ -e "$env_file" || -e "$s3_file" ]]; then
  fail "deploy/free/.env or s3.json already exists. To start over, delete both AND the Docker volumes
(./deploy/free/polygraph.sh down -v), because Postgres keeps the password it was first started with."
fi

echo "Polygraph Cloud: creating the server settings."
echo

read -rp "Web address, without https:// (for example polygraph-yourname.duckdns.org): " site
site="${site,,}"
[[ "$site" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] ||
  fail "\"$site\" isn't a plain host name."

echo "Where does this server run?"
echo "  1) Oracle Cloud, Mumbai"
echo "  2) Oracle Cloud, Hyderabad"
read -rp "Choose 1 or 2: " choice
case "$choice" in
  1) hosting=oracle-mumbai ;;
  2) hosting=oracle-hyderabad ;;
  *) fail "choose 1 or 2." ;;
esac

echo
echo "Contact email for security reports and privacy complaints. The DPDP Act needs a"
echo "grievance contact that works, and this address is shown publicly on the site,"
echo "so consider a separate address just for this."
read -rp "Contact email: " contact
[[ "$contact" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]] || fail "\"$contact\" isn't an email address."

origin="$(git -C "$here" remote get-url origin 2>/dev/null || true)"
origin="${origin%.git}"
origin="${origin/#git@github.com:/https://github.com/}"
read -rp "Public source repository [${origin:-https://github.com/you/polygraph}]: " source_url
source_url="${source_url:-$origin}"
[[ "$source_url" =~ ^https://github\.com/[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$ ]] ||
  fail "use the repository's https://github.com/<owner>/<repo> address."

echo
echo "GitHub App details (github.com > Settings > Developer settings > GitHub Apps > your app):"
read -rp "  App ID (a number): " app_id
[[ "$app_id" =~ ^[0-9]+$ ]] || fail "the App ID is a number."
read -rp "  Client ID: " client_id
[[ "$client_id" =~ ^[A-Za-z0-9._-]+$ ]] || fail "that doesn't look like a client ID."
read -rp "  App slug (the <slug> in github.com/apps/<slug>): " slug
[[ "$slug" =~ ^[a-z0-9-]+$ ]] || fail "the slug has only lower-case letters, digits and dashes."
read -rsp "  Client secret (hidden as you type): " client_secret
echo
[[ "$client_secret" =~ ^[A-Za-z0-9]+$ ]] || fail "that doesn't look like a client secret."
read -rp "  Path to the private key file (.pem) on this server: " pem_path
pem_path="${pem_path/#\~/$HOME}"
[[ -f "$pem_path" ]] || fail "no file at $pem_path."
grep -q -- "-----BEGIN .*PRIVATE KEY-----" "$pem_path" || fail "$pem_path isn't a PEM private key."
# One line with literal \n escapes; the API turns them back into newlines.
private_key="$(awk 'NF { printf "%s\\n", $0 }' "$pem_path")"

rand_b64() { openssl rand -base64 "$1" | tr -d '\n'; }
session_secret="$(rand_b64 48)"
fernet_key="$(openssl rand -base64 32 | tr '+/' '-_' | tr -d '\n')"
pg_password="$(openssl rand -hex 24)"
s3_access="$(openssl rand -hex 12)"
s3_secret="$(openssl rand -hex 24)"

umask 077
cat >"$env_file" <<EOF
# Polygraph Cloud server settings, generated by init-env.sh on $(date -u +%Y-%m-%d).
# This file holds secrets. Never commit it, copy it off the server or paste it anywhere.

# --- Address ---------------------------------------------------------------
SITE_ADDRESS=$site
PUBLIC_BASE_URL=https://$site
# GitHub Actions uploads must request this audience (the action's "audience" input).
OIDC_AUDIENCE=https://$site
# Quoted by the privacy notice, consent page and footer.
HOSTING=$hosting
PRIVACY_VERSION=2026-10-13
SOURCE_URL=$source_url
SECURITY_EMAIL=$contact
GRIEVANCE_EMAIL=$contact
# Empty: there is no status page.
STATUS_URL=

# --- Database --------------------------------------------------------------
POSTGRES_USER=polygraph
POSTGRES_DB=polygraph
POSTGRES_PASSWORD='$pg_password'

# --- File storage (the S3 server inside this stack) -------------------------
S3_BUCKET=polygraph-results
LOCAL_S3_ACCESS_KEY='$s3_access'
LOCAL_S3_SECRET_KEY='$s3_secret'

# --- GitHub App --------------------------------------------------------------
GITHUB_APP_ID=$app_id
GITHUB_APP_CLIENT_ID=$client_id
GITHUB_APP_SLUG=$slug
GITHUB_APP_CLIENT_SECRET='$client_secret'
GITHUB_APP_PRIVATE_KEY='$private_key'

# --- App secrets -------------------------------------------------------------
SESSION_SECRET='$session_secret'
TOKEN_ENCRYPTION_KEY='$fernet_key'

# --- Other -------------------------------------------------------------------
PII_SCANNER=regex
LOG_LEVEL=INFO
LEADERBOARD_PROJECT=polygraph-dev/benchmark
EOF

# The S3 server reads this inside its container, so it can't be private to
# your user. It is only reachable inside the Docker network.
umask 022
cat >"$s3_file" <<EOF
{
  "identities": [
    {
      "name": "polygraph",
      "credentials": [{ "accessKey": "$s3_access", "secretKey": "$s3_secret" }],
      "actions": ["Admin", "Read", "Write", "List", "Tagging"]
    }
  ]
}
EOF

echo
echo "Wrote deploy/free/.env (only you can read it) and deploy/free/s3.json."
read -rp "Delete the private key file $pem_path now? It's copied into .env. [y/N] " del
if [[ "${del,,}" == y* ]]; then
  if command -v shred >/dev/null; then shred -u "$pem_path"; else rm -f "$pem_path"; fi
  echo "Deleted."
else
  echo "Kept. Delete it yourself once the site works."
fi
echo
echo "Next: ./deploy/free/polygraph.sh up -d --build"
